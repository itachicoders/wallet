pub fn get_network(id: NetworkId) -> &'static NetworkSpec {
    NETWORKS.iter().find(|n| n.id == id).expect("Network not found in registry")
}

pub fn get_networks_by_family(family: NetworkFamily) -> Vec<&'static NetworkSpec> {
    NETWORKS.iter().filter(|n| n.family == family).collect()
}

pub fn get_usdt_networks() -> Vec<&'static NetworkSpec> {
    NETWORKS.iter().filter(|n| n.usdt_contract.is_some()).collect()
}
